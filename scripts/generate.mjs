const doc = JSON.parse(readFileSync(OPENAPI, "utf8"));
const API = "https://api.rumoro.dev";
const METHODS = ["get", "post", "put", "patch", "delete"];

const resolve = (schema) => {
  let s = schema ?? {};
  for (let i = 0; s.$ref && i < 10; i++) s = s.$ref.split("/").slice(1).reduce((node, key) => node[key], doc);
  return s;
};
const cell = (text) => String(text ?? "").replace(/\s+/g, " ").replace(/\|/g, "\\|").trim();
function typeOf(schema) {
  const s = resolve(schema);
  const variants = s.anyOf ?? s.oneOf;
  if (variants) return [...new Set(variants.map(typeOf))].join(" or ");
  let type;
  if (s.enum) type = s.enum.map((value) => `\`${value}\``).join(", ");
  else if (s.type === "array") type = resolve(s.items).enum ? `list of ${typeOf(s.items)}` : `${typeOf(s.items)}[]`;
  else type = s.type ?? (s.properties ? "object" : "any");
  return s.nullable ? `${type} or null` : type;
}
function fields(schema, prefix = "", depth = 0) {
  const s = resolve(schema);
  const props = s.properties ?? {};
  const required = new Set(s.required ?? []);
  const rows = [];
  for (const [name, raw] of Object.entries(props)) {
    const prop = resolve(raw);
    rows.push(`| \`${prefix}${name}\` | ${cell(typeOf(prop))} | ${required.has(name) ? "yes" : ""} | ${cell(prop.description)} |`);
    const nested = prop.type === "array" ? resolve(prop.items) : prop;
    if (depth < 1 && nested.properties) rows.push(...fields(nested, `${prefix}${name}${prop.type === "array" ? "[]" : ""}.`, depth + 1));
  }
  return rows;
}
const operations = Object.entries(doc.paths).flatMap(([path, item]) =>
  METHODS.filter((method) => item[method]).map((method) => ({ path, method, ...item[method] })));

function renderOperation(op) {
  const out = [`### \`${op.method.toUpperCase()} ${op.path}\`: ${op.summary ?? op.operationId}`, ""];
  if (op.description) out.push(op.description, "");
  out.push(`CLI: \`rumoro ${commandName({ operationId: op.operationId, method: op.method, path: op.path })}\``, "");
  const params = op.parameters ?? [];
  if (params.length) {
    out.push("| Parameter | In | Type | Required | Description |", "| --- | --- | --- | --- | --- |");
    for (const p of params) out.push(`| \`${p.name}\` | ${p.in} | ${cell(typeOf(p.schema))} | ${p.required ? "yes" : ""} | ${cell(p.description ?? resolve(p.schema).description)} |`);
    out.push("");
  }
  const body = op.requestBody?.content?.["application/json"]?.schema;
  if (body) {
    const rows = fields(body);
    if (rows.length) out.push("Body (JSON):", "", "| Field | Type | Required | Description |", "| --- | --- | --- | --- |", ...rows, "");
  }
  const answers = Object.entries(op.responses ?? {}).filter(([status]) => /^2/.test(status)).map(([status, response]) => {
    const schema = resolve(response.content?.["application/json"]?.schema);
    const keys = Object.keys(schema.properties ?? {});
    return `\`${status}\`${keys.length ? ` with ${keys.map((key) => `\`${key}\``).join(", ")}` : ""}${response.description ? `: ${cell(response.description)}` : ""}`;
  });
  if (answers.length) out.push(`Answers ${answers.join("; ")}.`, "");
  return out.join("\n");
}

function renderArea(area) {
  const ops = operations.filter((op) => area.tags.includes(op.tags?.[0]));
  return [BANNER, "", `# ${area.title}`, "", area.intro, "",
    `Base URL \`${API}\`, \`Authorization: Bearer $RUMORO_API_KEY\` on every request, JSON in and out. Each endpoint names its \`rumoro\` CLI command for when the CLI is installed (rules/cli.md).`, "",
    "## Endpoints", "", ...ops.map(renderOperation)].join("\n").trimEnd() + "\n";
}

function renderErrors() {
  const codes = resolve(doc.components.schemas.ErrorResponse).properties.error.properties.code.enum;
  return [BANNER, "", "# Errors", "",
    "Every error is `{ \"error\": { \"code\", \"message\", \"requestId\" } }`. Branch on `code`, not on the message. The common ones:", "",
    "- `401 unauthorized`: the key is missing or wrong. Stop and tell the user how to set `RUMORO_API_KEY` (SKILL.md, Setup).",
    "- `403 read_only_key`: the key can read but not write. Ask for a `write` key.",
    "- `404 not_found`: no such id in this workspace (an id from another workspace is a `404`, never a `403`).",
    "- `400 validation_error`: the message names the field. Fix the request; don't retry it unchanged.",
    "- `402 insufficient_balance` or `keyword_limit_reached`: point the user to the Billing page of the dashboard rather than retrying.",
    "- `409 duplicate_keyword`: the term is already tracked in that group. List the keywords and use the existing one.",
    "- `429 rate_limited`: wait for `Retry-After`, then retry once.", "",
    "## Every code", "", "The API's full list, from its OpenAPI document:", "",
    ...codes.map((code) => `- \`${code}\``)].join("\n") + "\n";
}

function renderSkill() {
  const guide = agentGuide(ORIGIN);
  const section = (title) => {
    const start = guide.indexOf(`\n## ${title}\n`);
    if (start < 0) throw new Error(`OpenClaw skill: the agent guide has no "${title}" section`);
    const end = guide.indexOf("\n## ", start + 4);
    return guide.slice(start + 1, end < 0 ? undefined : end).trimEnd();
  };
  const frontmatter = readFileSync(join(HERE, "frontmatter.yml"), "utf8").trim();
  return [frontmatter, "", BANNER, "", "# Rumoro", "",
    "Rumoro collects public posts that mention the terms a team tracks, rates each one for relevance, sentiment and intent, and serves the results through a REST API. This skill drives that API with curl or the `rumoro` CLI. Open the matching file in `rules/` before working in an area for the first time.", "",
    `- Base URL: \`${API}/v1\``, "- Auth: `Authorization: Bearer $RUMORO_API_KEY` on every request",
    `- Contract: \`${API}/v1/openapi.json\` lists every operation, field and error`,
    "- Docs: https://docs.rumoro.dev (add `.mdx` to any page's address for its Markdown)", "",
    "## Setup", "",
    "Every request needs a key in `RUMORO_API_KEY`. If it's missing, or a request comes back `401`, stop and walk the user through these steps:", "",
    "1. Create a key on the API keys page at https://app.rumoro.dev. With `write` scope the whole skill works; with `read` it can search and read analytics and people, but can't change anything.",
    "2. Add it to the file the Gateway loads: `echo 'RUMORO_API_KEY=ref_...' >> ~/.openclaw/.env`",
    "3. Restart the Gateway: `openclaw gateway restart`", "",
    "Don't repeat the key back, store it anywhere the user didn't ask for, or send it to any host but `api.rumoro.dev`. To test a key, `GET /v1/keywords`: `401` means it's wrong, an empty list means nothing is tracked yet.", "",
    section("Making requests"), "", section("Conventions"), "", section("Requests and the calls behind them"), "", section("Before you act"), "",
    "## Rule files", "", "Each file covers one area in detail:", "",
    ...AREAS.map((area) => `- [rules/${area.slug}.md](rules/${area.slug}.md): ${area.title.toLowerCase()}`),
    "- [rules/authentication.md](rules/authentication.md): keys, scopes and where they come from",
    "- [rules/errors.md](rules/errors.md): every error code and what to do about the common ones",
    "- [rules/cli.md](rules/cli.md): the `rumoro` command line tool, both SDKs and the OpenAPI document"].join("\n") + "\n";
}

// Every operation must belong to an area, so nothing in the API goes missing from the skill.
const covered = new Set(AREAS.flatMap((area) => area.tags));
const uncovered = [...new Set(operations.map((op) => op.tags?.[0]).filter((tag) => !covered.has(tag)))];
if (uncovered.length) throw new Error(`OpenClaw skill: no rule file covers the ${uncovered.join(", ")} endpoints; add them to AREAS`);

const files = new Map([["SKILL.md", renderSkill()], ["rules/errors.md", renderErrors()], ...AREAS.map((area) => [`rules/${area.slug}.md`, renderArea(area)])]);
const check = process.argv.includes("--check");
let stale = 0;
for (const [name, content] of files) {
  const path = join(SKILL, name);
  let current = null;
  try { current = readFileSync(path, "utf8"); } catch { /* not written yet */ }
  if (current === content) continue;
  if (check) { console.error(`stale: skill/${name}`); stale++; continue; }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
  console.log(`wrote skill/${name}`);
}
if (check && stale) process.exit(1);
