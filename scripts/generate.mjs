const SKILL = join(HERE, "..", "skill");
const OPENAPI = join(HERE, "..", "..", "sdk", "openapi.json");
const ORIGIN = "https://app.rumoro.dev";
const BANNER = "<!-- Generated by packages/openclaw-skill/scripts/generate.mjs. Do not edit: change the API, the agent guide or the prose in the script, then regenerate. -->";

// The area files: which OpenAPI tags each covers, and a short introduction stated from the agent guide.
